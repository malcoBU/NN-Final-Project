"""
dataset.py
----------
PyTorch Dataset and DataLoader for AlphaSound.

Expected structure under data/processed/
-----------------------------------------
processed/
  english/
    a_EN_1.npy   a_EN_2.npy   b_EN_1.npy   ...
  spanish/
    a_ES_1.npy   b_ES_1.npy   ...

Each .npy is a preprocessed waveform (float32, 16 kHz) generated by
preprocess.preprocess_directory(). The letter is extracted from the first
character of the filename; the language comes from the parent folder name.

Only the 26 letters of the common Latin alphabet (a–z) are used.
Data augmentation is applied to the waveform BEFORE extracting features,
so it works exactly the same as with .wav files.
"""

import os
import json
import random
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader, WeightedRandomSampler

from augment   import augment
from features  import extract_features, normalize_spectrogram

# ── Labels ────────────────────────────────────────────────────────────────────

LANGUAGE_TO_IDX: dict[str, int] = {
    "english": 0,
    "spanish": 1,
}

# 26 common letters + ñ (Spanish-exclusive) = 27 classes
ALL_LETTERS: list[str] = list("abcdefghijklmnopqrstuvwxyz") + ["ñ"]

LETTER_TO_IDX: dict[str, int] = {l: i for i, l in enumerate(ALL_LETTERS)}
IDX_TO_LETTER: dict[int, str] = {i: l for l, i in LETTER_TO_IDX.items()}
IDX_TO_LANG:   dict[int, str] = {v: k for k, v in LANGUAGE_TO_IDX.items()}

# Vowel subset (useful for reduced experiments)
VOWELS: list[str] = ["a", "e", "i", "o", "u"]


def build_subset_maps(
    letters_subset: list[str],
) -> tuple[dict[str, int], dict[int, str]]:
    """
    Build contiguous index maps for a subset of letters.

    Example: letters_subset=['a','e','i','o','u']
      → subset_letter_to_idx = {'a':0, 'e':1, 'i':2, 'o':3, 'u':4}
      → subset_idx_to_letter = {0:'a', 1:'e', 2:'i', 3:'o', 4:'u'}

    Parameters
    ----------
    letters_subset : list[str]
        List of letters to include (must exist in ALL_LETTERS).

    Returns
    -------
    (subset_letter_to_idx, subset_idx_to_letter)
    """
    unknown = [l for l in letters_subset if l not in LETTER_TO_IDX]
    if unknown:
        raise ValueError(f"Unknown letters in subset: {unknown}")
    ordered = sorted(letters_subset, key=lambda l: LETTER_TO_IDX[l])
    s2i = {l: i for i, l in enumerate(ordered)}
    i2s = {i: l for l, i in s2i.items()}
    return s2i, i2s


# ── Dataset ───────────────────────────────────────────────────────────────────

class AlphaSoundDataset(Dataset):
    """
    Loads preprocessed waveforms in .npy format, applies optional augmentation,
    and extracts mel-spectrogram features.

    Returns tuples (tensor, letter_idx, lang_idx).

    Parameters
    ----------
    root_dir : str
        Path to the directory containing the processed .npy files
        (contains subdirectories 'english/' and 'spanish/').
    split : str
        'train', 'val', or 'test'.
    split_ratios : tuple[float, float, float]
        Train/val/test proportions. Must sum to 1.0.
    augment_prob : float
        Probability of applying augmentation to each training sample.
        Ignored in val/test (forced to 0).
    normalize : bool
        If True, standardises each spectrogram to zero mean / unit variance.
    seed : int
        Seed for reproducibility of the split.
    """

    def __init__(
        self,
        root_dir: str,
        split: str = "train",
        split_ratios: tuple = (0.70, 0.15, 0.15),
        augment_prob: float = 0.8,
        normalize: bool = True,
        seed: int = 42,
        letters_subset: list[str] | None = None,
    ):
        """
        Additional parameters
        ---------------------
        letters_subset : list[str] | None
            If specified, only samples whose letter is in this list are loaded,
            and indices are remapped to contiguous values (0…len(subset)-1).
            Use VOWELS to filter vowels only.
            If None (default), all letters in ALL_LETTERS are used.

        Usage example
        -------------
            from dataset import AlphaSoundDataset, VOWELS
            ds = AlphaSoundDataset("data/processed", letters_subset=VOWELS)
            # ds returns letter_idx in {0,1,2,3,4} → a,e,i,o,u
        """
        assert split in ("train", "val", "test"), \
            f"split must be 'train', 'val', or 'test', got: '{split}'"
        assert abs(sum(split_ratios) - 1.0) < 1e-6, \
            "split_ratios must sum to 1.0"

        self.root_dir     = Path(root_dir)
        self.split        = split
        self.augment_prob = augment_prob if split == "train" else 0.0
        self.normalize    = normalize

        # ── Letter subset ─────────────────────────────────────────────────────
        if letters_subset is not None:
            self.subset_letter_to_idx, self.subset_idx_to_letter = \
                build_subset_maps(letters_subset)
            self._subset_set = set(letters_subset)
        else:
            self.subset_letter_to_idx  = None
            self.subset_idx_to_letter  = None
            self._subset_set           = None

        # ── Speaker-level split ───────────────────────────────────────────────
        # With few speakers, splitting by sample gives inflated metrics because
        # the model sees the same voices in train and val.
        # The only way to measure real generalisation is to reserve entire
        # speakers for val/test — voices the model has never heard.
        #
        # Example with 10 speakers and 70/15/15 ratios:
        #   Train → speakers 1–7   (+ all their augmented versions)
        #   Val   → speakers 8–9   (originals only)
        #   Test  → speaker  10    (originals only)
        originals, augmented = self._scan_directory()

        if not originals:
            raise RuntimeError(
                f"No .npy files found under '{root_dir}'."
            )

        # 1. Get sorted unique speaker IDs
        all_speakers = sorted(set(s["speaker_id"] for s in originals))
        n_speakers   = len(all_speakers)

        # 2. Split speaker IDs into train/val/test
        random.seed(seed)
        speakers_shuffled = all_speakers.copy()
        random.shuffle(speakers_shuffled)

        n_train_spk = max(1, int(n_speakers * split_ratios[0]))
        n_val_spk   = max(1, int(n_speakers * split_ratios[1]))

        train_speakers = set(speakers_shuffled[:n_train_spk])
        val_speakers   = set(speakers_shuffled[n_train_spk : n_train_spk + n_val_spk])
        test_speakers  = set(speakers_shuffled[n_train_spk + n_val_spk :])

        # If no speakers remain for test, move the last val speaker to test
        if not test_speakers and len(val_speakers) > 1:
            last_val = sorted(val_speakers)[-1]
            val_speakers.remove(last_val)
            test_speakers.add(last_val)

        # 3. Assign samples to the corresponding split
        #    Augmented: train split only, and only if their speaker is in train
        if split == "train":
            orig_split = [s for s in originals if s["speaker_id"] in train_speakers]
            aug_split  = [s for s in augmented if s["speaker_id"] in train_speakers]
            self.samples = orig_split + aug_split
        elif split == "val":
            self.samples = [s for s in originals if s["speaker_id"] in val_speakers]
        else:
            self.samples = [s for s in originals if s["speaker_id"] in test_speakers]

        # 4. Filter by letter subset (if specified)
        if self._subset_set is not None:
            before = len(self.samples)
            self.samples = [
                s for s in self.samples
                if IDX_TO_LETTER[s["letter_idx"]] in self._subset_set
            ]
            # Remap letter_idx to contiguous subset indices
            self.samples = [
                {**s, "letter_idx": self.subset_letter_to_idx[IDX_TO_LETTER[s["letter_idx"]]]}
                for s in self.samples
            ]
            after = len(self.samples)
            if split == "train":
                print(f"  Active subset   : {sorted(self._subset_set)}  "
                      f"({before} → {after} samples)")

        # Informational log
        if split == "train":
            print(f"  Train speakers  : {sorted(train_speakers)}")
            print(f"  Val speakers    : {sorted(val_speakers)}")
            print(f"  Test speakers   : {sorted(test_speakers)}")

    # ── Internal helpers ──────────────────────────────────────────────────────

    @staticmethod
    def _extract_speaker_id(stem: str) -> str:
        """
        Extract the speaker ID from the filename stem.

        Expected format: letter_LANG_speaker  (e.g. 'a_EN_1', 'z_ES_10')
        For augmented:   letter_LANG_speaker_aug_N  (e.g. 'a_EN_1_aug_03')

        Returns the ID as a string (e.g. '1', '10').
        """
        base = stem.split("_aug_")[0]   # strip augmentation suffix if present
        return base.split("_")[-1]      # last segment = speaker ID

    def _scan_directory(self) -> tuple[list[dict], list[dict]]:
        """
        Walk root_dir looking for .npy files and split them into two lists:
        originals and augmented (_aug_).

        Extracts letter, language, and speaker_id from the filename:
          • Letter      → first character  (e.g. 'a_EN_1.npy' → 'a')
          • Language    → '_EN_' → english (0), '_ES_' → spanish (1)
          • Speaker ID  → last number      (e.g. 'a_EN_1.npy' → '1')

        Returns
        -------
        (originals, augmented) — two lists of dicts
            {"path": str, "letter_idx": int, "lang_idx": int, "speaker_id": str}
        """
        originals = []
        augmented = []

        for npy_file in sorted(self.root_dir.rglob("*.npy")):
            stem = npy_file.stem  # e.g. 'a_EN_1' or 'a_EN_1_aug_01'

            # ── Letter: first character ───────────────────────────────────────
            letter = stem[0].lower()
            if letter not in LETTER_TO_IDX:
                continue

            # ── Language: '_EN_' or '_ES_' in the name ────────────────────────
            stem_upper = stem.upper()
            if "_EN_" in stem_upper:
                lang_idx = LANGUAGE_TO_IDX["english"]
            elif "_ES_" in stem_upper:
                lang_idx = LANGUAGE_TO_IDX["spanish"]
            else:
                continue

            # ── Speaker ID ────────────────────────────────────────────────────
            speaker_id = self._extract_speaker_id(stem)

            entry = {
                "path":       str(npy_file),
                "letter_idx": LETTER_TO_IDX[letter],
                "lang_idx":   lang_idx,
                "speaker_id": speaker_id,
            }

            if "_aug_" in stem:
                augmented.append(entry)
            else:
                originals.append(entry)

        return originals, augmented

    # ── PyTorch interface ─────────────────────────────────────────────────────

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int, int]:
        """
        Returns
        -------
        mel_tensor : torch.Tensor, shape (1, 128, 128), float32
        letter_idx : int
        lang_idx   : int
        """
        sample = self.samples[idx]

        # Load preprocessed waveform from .npy
        y = np.load(sample["path"])

        # Augmentation on the waveform (training only)
        if self.augment_prob > 0:
            y = augment(y, p_apply=self.augment_prob)

        # Extract mel-spectrogram → numpy (1, 128, 128)
        mel = extract_features(y)

        # Per-instance normalisation
        if self.normalize:
            mel = normalize_spectrogram(mel)

        return (
            torch.from_numpy(mel),
            sample["letter_idx"],
            sample["lang_idx"],
        )

    # ── Utilities ─────────────────────────────────────────────────────────────

    def class_weights(self) -> torch.Tensor:
        """
        Weights inversely proportional to the frequency of each letter class.
        Useful for WeightedRandomSampler when there is class imbalance.

        Returns
        -------
        weights : torch.Tensor, shape (len(self),)
        """
        from collections import Counter

        counts   = Counter(s["letter_idx"] for s in self.samples)
        n_classes = len(LETTER_TO_IDX)

        freq = torch.zeros(n_classes)
        for idx, cnt in counts.items():
            freq[idx] = cnt

        class_w = 1.0 / (freq + 1e-8)
        class_w[freq == 0] = 0.0

        return torch.tensor(
            [class_w[s["letter_idx"]].item() for s in self.samples]
        )

    def n_letters(self) -> int:
        """Number of active letter classes (27 by default, fewer if a subset is used)."""
        if self.subset_letter_to_idx is not None:
            return len(self.subset_letter_to_idx)
        return len(LETTER_TO_IDX)

    def summary(self) -> str:
        """Brief summary of the split."""
        from collections import Counter
        # With subset, letter_idx is already remapped → use subset_idx_to_letter
        i2l = self.subset_idx_to_letter if self.subset_idx_to_letter else IDX_TO_LETTER
        letter_counts = Counter(i2l[s["letter_idx"]] for s in self.samples)
        lang_counts   = Counter(IDX_TO_LANG[s["lang_idx"]] for s in self.samples)
        subset_note   = (
            f"  Subset : {sorted(self._subset_set)}\n"
            if self._subset_set else ""
        )
        return (
            f"Split    : {self.split}\n"
            f"{subset_note}"
            f"Total    : {len(self.samples)} samples\n"
            f"Languages: {dict(lang_counts)}\n"
            f"Letters (top-5): {letter_counts.most_common(5)}"
        )


# ── DataLoader factory ────────────────────────────────────────────────────────

def build_dataloaders(
    root_dir: str,
    batch_size: int = 32,
    num_workers: int = 4,
    augment_prob: float = 0.8,
    normalize: bool = True,
    use_weighted_sampler: bool = True,
    seed: int = 42,
    letters_subset: list[str] | None = None,
) -> tuple[DataLoader, DataLoader, DataLoader]:
    """
    Build train, val, and test DataLoaders in a single call.

    Parameters
    ----------
    root_dir : str
        Root directory containing the .npy files (english/ and spanish/).
    batch_size : int
    num_workers : int
        Set to 0 on Windows or if multiprocessing causes issues.
    augment_prob : float
        Augmentation probability during training.
    normalize : bool
        Per-instance normalisation of the spectrogram.
    use_weighted_sampler : bool
        If True, use WeightedRandomSampler in train to balance classes.
    seed : int
    letters_subset : list[str] | None
        Subset of letters to classify. If None, all letters are used.
        Example: letters_subset=VOWELS  → vowels only (5 classes).
        Letter indices are automatically remapped to 0…len(subset)-1.

    Returns
    -------
    (train_loader, val_loader, test_loader)
    """
    train_ds = AlphaSoundDataset(root_dir, "train", augment_prob=augment_prob,
                                 normalize=normalize, seed=seed,
                                 letters_subset=letters_subset)
    val_ds   = AlphaSoundDataset(root_dir, "val",   augment_prob=0.0,
                                 normalize=normalize, seed=seed,
                                 letters_subset=letters_subset)
    test_ds  = AlphaSoundDataset(root_dir, "test",  augment_prob=0.0,
                                 normalize=normalize, seed=seed,
                                 letters_subset=letters_subset)

    print(train_ds.summary())
    print(val_ds.summary())
    print(test_ds.summary())

    train_sampler = None
    if use_weighted_sampler:
        weights       = train_ds.class_weights()
        train_sampler = WeightedRandomSampler(
            weights, num_samples=len(train_ds), replacement=True
        )

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        sampler=train_sampler,
        shuffle=(train_sampler is None),
        num_workers=num_workers,
        pin_memory=True,
        drop_last=True,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )
    test_loader = DataLoader(
        test_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )

    return train_loader, val_loader, test_loader


# ── Label utilities (used by train.py and evaluate.py) ───────────────────────

def decode_predictions(
    letter_logits: torch.Tensor,
    lang_logits: torch.Tensor,
    idx_to_letter: dict[int, str] | None = None,
) -> list[dict]:
    """
    Convert raw model logits into human-readable predictions.

    Parameters
    ----------
    letter_logits : torch.Tensor, shape (B, N_letters)
    lang_logits   : torch.Tensor, shape (B, 2)
    idx_to_letter : dict[int, str] | None
        Index→letter map. If None, uses the global IDX_TO_LETTER (27 classes).
        Pass dataset.subset_idx_to_letter when using letters_subset.

    Returns
    -------
    list of dicts {"letter": str, "language": str,
                   "letter_conf": float, "lang_conf": float}
    """
    i2l = idx_to_letter if idx_to_letter is not None else IDX_TO_LETTER

    letter_probs = torch.softmax(letter_logits, dim=-1)
    lang_probs   = torch.softmax(lang_logits,   dim=-1)

    letter_idx = letter_probs.argmax(dim=-1).tolist()
    lang_idx   = lang_probs.argmax(dim=-1).tolist()

    results = []
    for li, la in zip(letter_idx, lang_idx):
        results.append({
            "letter":      i2l[li],
            "language":    IDX_TO_LANG[la],
            "letter_conf": round(letter_probs[letter_idx.index(li)][li].item(), 4),
            "lang_conf":   round(lang_probs[lang_idx.index(la)][la].item(), 4),
        })
    return results


def save_label_maps(output_path: str = "data/label_maps.json") -> None:
    """Save LETTER_TO_IDX and LANGUAGE_TO_IDX to JSON for inference."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    data = {
        "letter_to_idx": LETTER_TO_IDX,
        "lang_to_idx":   LANGUAGE_TO_IDX,
    }
    with open(output_path, "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    print(f"Label maps saved to {output_path}")
